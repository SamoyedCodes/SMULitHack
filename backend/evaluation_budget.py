"""One durable, fail-closed OpenRouter campaign. No credentials enter the ledger."""
import hashlib
import json
import re
import time
from decimal import Decimal, InvalidOperation

import httpx

from .llm import ProviderFailure

MODEL = 'z-ai/glm-5.3-flash'
CEILING = Decimal('14')
MAX_OUTPUT = 16384


class BudgetStop(ProviderFailure):
    pass


def money(value):
    try:
        result = Decimal(str(value))
        if not result.is_finite() or result < 0:
            raise ValueError()
        return result
    except (ValueError, InvalidOperation):
        raise BudgetStop('Missing or invalid pricing/usage; inference stopped.') from None


def select_endpoint(data):
    """Pin one advertised endpoint, including its context and all billable price bounds."""
    if data.get('id') != MODEL:
        raise BudgetStop('The configured evaluation model is unavailable.')
    eligible = []
    for endpoint in data.get('endpoints', []):
        parameters = set(endpoint.get('supported_parameters', []))
        if (endpoint.get('status') != 0 or not
                {'structured_outputs', 'response_format', 'max_tokens', 'reasoning'} <= parameters):
            continue
        if not isinstance(endpoint.get('context_length'), int) or endpoint['context_length'] < MAX_OUTPUT:
            continue
        if (endpoint.get('max_completion_tokens') or 0) < MAX_OUTPUT:
            continue
        prices = endpoint.get('pricing', {})
        prompt, completion = money(prices.get('prompt')), money(prices.get('completion'))
        # Only text inference is enabled. Reject unbounded extra charges, including request fees.
        if any(money(v) > 0 for k, v in prices.items()
               if k not in {'prompt', 'completion', 'input_cache_read', 'discount'}):
            continue
        if money(prices.get('input_cache_read', 0)) > prompt:
            continue
        if not endpoint.get('tag'):
            continue
        eligible.append((prompt + completion, endpoint['tag'], {
            'tag': endpoint['tag'], 'context_length': endpoint['context_length'],
            'prompt': str(prompt), 'completion': str(completion), 'checked_at': time.time(),
        }))
    if not eligible:
        raise BudgetStop('No available endpoint has verified structured output and bounded text pricing.')
    return min(eligible, key=lambda x: x[:2])[2]


class EvaluationBudget:
    def __init__(self, store, document_ids, endpoint):
        if len(document_ids) != 10 or len(set(document_ids)) != 10:
            raise BudgetStop('The evaluation requires exactly ten unique manifest documents.')
        self.store, self.ids, self.endpoint = store, set(document_ids), endpoint
        with store.connection() as db:
            db.execute('CREATE TABLE IF NOT EXISTS evaluation_requests ('
                       'fingerprint TEXT PRIMARY KEY, reservation TEXT NOT NULL, cost TEXT, '
                       'state TEXT NOT NULL, body TEXT, created REAL NOT NULL)')

    def summary(self):
        with self.store.connection() as db:
            rows = db.execute('SELECT reservation,cost,state FROM evaluation_requests').fetchall()
        actual = sum((money(r['cost']) for r in rows if r['cost'] is not None), Decimal(0))
        reserved = sum((money(r['reservation']) for r in rows if r['cost'] is None), Decimal(0))
        return {'ceiling_usd': str(CEILING), 'charged_usd': str(actual),
                'unreconciled_reserved_usd': str(reserved), 'requests': len(rows),
                'unreconciled_requests': sum(r['state'] != 'settled' for r in rows)}

    def send(self, client, body, api_key):
        if body.get('model') != MODEL:
            raise BudgetStop('Model switching is forbidden in this evaluation.')
        # Page headers are generated by the existing application, not by model output.
        supplied = body['messages'][-1]['content'].split('\nUNTRUSTED DOCUMENT DATA:\n', 1)[-1]
        ids = set(re.findall(r'\[document_id=([^\s\]]+)', supplied))
        if not ids or not ids <= self.ids:
            raise BudgetStop('Request contains missing or non-manifest document identities.')
        endpoint = self.endpoint
        if time.time() - endpoint['checked_at'] > 3600:
            raise BudgetStop('Pricing preflight expired; refresh it before resuming.')
        body['max_tokens'] = MAX_OUTPUT
        body['reasoning'] = {'enabled': False}
        body['provider'].update({'only': [endpoint['tag']], 'allow_fallbacks': False,
                                'max_price': {'prompt': float(money(endpoint['prompt']) * 1000000),
                                              'completion': float(money(endpoint['completion']) * 1000000)}})
        fingerprint = hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()
        # Reserve the entire advertised context, rather than guessing a tokenizer's input count.
        reserve = (money(endpoint['prompt']) * endpoint['context_length'] +
                   money(endpoint['completion']) * MAX_OUTPUT)
        with self.store.connection() as db:
            db.execute('BEGIN IMMEDIATE')
            rows = db.execute('SELECT * FROM evaluation_requests').fetchall()
            if any(r['state'] != 'settled' for r in rows):
                raise BudgetStop('A previous charge is unaccounted for. No further request was sent.')
            previous = next((r for r in rows if r['fingerprint'] == fingerprint), None)
            if previous:
                saved = json.loads(previous['body'])
                return httpx.Response(saved['status'], json=saved['response'])
            total = sum((money(r['cost']) for r in rows), Decimal(0))
            if total + reserve > CEILING:
                raise BudgetStop('The next request would exceed the US$14 reserved execution ceiling.')
            db.execute('INSERT INTO evaluation_requests VALUES(?,?,NULL,?,NULL,?)',
                       (fingerprint, str(reserve), 'reserved', time.time()))
        try:
            response = client.post('https://openrouter.ai/api/v1/chat/completions',
                                   headers={'Authorization': 'Bearer ' + api_key}, json=body)
        except httpx.TransportError:
            raise BudgetStop('Transport outcome is uncertain; reservation retained and campaign stopped.') from None
        # Persist a receipt even for errors without usage, so a generation ID can be audited
        # later without repeating inference. This is local data, never printed or sent elsewhere.
        with self.store.connection() as db:
            db.execute('UPDATE evaluation_requests SET body=? WHERE fingerprint=?',
                       (json.dumps({'status': response.status_code, 'raw_response': response.text}), fingerprint))
        try:
            result = response.json()
            cost = money(result.get('usage', {}).get('cost'))
        except (ValueError, AttributeError, BudgetStop):
            raise BudgetStop('Response has no trustworthy usage cost; reservation retained and campaign stopped.') from None
        saved = json.dumps({'status': response.status_code, 'response': result})
        with self.store.connection() as db:
            db.execute('UPDATE evaluation_requests SET cost=?,state=?,body=? WHERE fingerprint=?',
                       (str(cost), 'settled' if cost <= reserve else 'over_reservation', saved, fingerprint))
        if cost > reserve:
            raise BudgetStop('Reported cost exceeded its reservation; campaign stopped.')
        if response.status_code == 200 and result.get('model') != MODEL:
            with self.store.connection() as db:
                db.execute("UPDATE evaluation_requests SET state='model_mismatch' WHERE fingerprint=?", (fingerprint,))
            raise BudgetStop('Response model differs from the authorized model; campaign stopped.')
        return response
